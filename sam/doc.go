// Package sam holds a Go struct of every SAM (Smarter Application Manifest) kind, generated from
// the Smarter platform's JSON Schemas.
//
// Each struct describes a complete manifest of its kind: apiVersion, kind, metadata, spec and the
// read-only status. Use them to build manifests in code, with your editor's completion, or to read
// a described manifest with typed fields:
//
//	manifest, err := client.Guardrails.Describe(ctx, "pii_redactor")
//	if err != nil {
//		return err
//	}
//	guardrail, err := smarter.ToSAM[sam.Guardrail](manifest)
//	if err != nil {
//		return err
//	}
//	fmt.Println(guardrail.Spec.Config.Action)
//
// A struct ignores the fields that it doesn't declare when it decodes a manifest, so that a manifest
// of a newer platform still decodes, but it doesn't keep them: apply a [smarter.Manifest] to keep
// every field. The platform's own models also enforce business rules that a JSON Schema can't
// express: validate a manifest with the client's Manifests.Validate before you rely on it.
//
// Every file of this package except this one and the tests is generated by internal/cmd/samgen:
// run make sam-models, and never edit them by hand.
package sam

// Manifest is implemented by the struct of every kind.
type Manifest interface {
	// SAMKind returns the manifest kind that the struct describes, e.g. "Guardrail".
	SAMKind() string
}
